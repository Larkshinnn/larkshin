"""Rebuild runs-data.js: scan every PPC (Ultimate) and Warzone (Hero, Legend) week on Huaxu
for the player, keep the top-100 appearances, and store the best five per mode with icons.

    python tools/update_runs.py

Takes a few minutes (one request per week, politely spaced). Not needed for deploys:
the site already re-checks the newest weeks live in the browser.
"""
import json, os, time, urllib.request

PLAYER = 26438993
BASE = "https://api.huaxu.app/servers/ap"
UA = {"User-Agent": "larkshinnn-profile/1.0", "Accept": "application/json"}
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "runs-data.js")

MODES = [  # key, title, tier, path builder
    ("ppc", "PPC", "Ultimate", lambda w: f"ppc/{w}/4?ranking=true"),
    ("hero", "Warzone", "Hero", lambda w: f"warzone/{w}/15"),
    ("legend", "Warzone", "Legend", lambda w: f"warzone/{w}/16"),
]


def get(path, tries=3):
    for i in range(tries):
        try:
            req = urllib.request.Request(f"{BASE}/{path}", headers=UA)
            with urllib.request.urlopen(req, timeout=30) as r:
                d = json.load(r)
            return d.get("data") if d.get("status") == "success" else None
        except Exception:
            time.sleep(2 + 3 * i)
    return None


def entry(key, data, week):
    rows = data.get("rankings") or data.get("ranking") or []
    r = next((x for x in rows if x["player"]["id"] == PLAYER), None)
    if not r:
        return None
    meta = data.get("warzone") or data.get("ppc") or {}
    e = {"week": week, "rank": r["rank"], "score": r["score"], "members": meta.get("members"),
         "start": (meta.get("start") or "")[:10], "end": (meta.get("end") or "")[:10]}
    if key == "ppc":
        e["bosses"] = [{"name": b["name"], "icon": b["icon"]} for b in meta.get("bosses", [])]
    else:
        zname = {z["id"]: z["name"] for z in (meta.get("area") or {}).get("zones", [])}
        e["zones"] = [{"name": zname.get(z["id"], ""), "score": z["score"],
                       "team": [{"name": c["characterName"], "frame": c["frameName"], "icon": c["icon"]} for c in z.get("characters", [])]}
                      for z in r.get("zones", [])]
    return e


out = {"scannedAt": time.strftime("%Y-%m-%d"), "modes": []}
for key, title, tier, path in MODES:
    probe = get(path(1)) or {}
    rng = probe.get("activities") or {}
    if not rng:  # week 1 may not exist; fall back to a known-good recent week
        rng = (get(path(467 if key != "ppc" else 279)) or {}).get("activities", {})
    lo, hi = rng["min"], rng["max"]
    found = []
    for w in range(hi, lo - 1, -1):
        data = get(path(w))
        if data:
            e = entry(key, data, w)
            if e:
                found.append(e)
        time.sleep(0.25)
    print(f"{key}: weeks {lo}-{hi}, in top 100 {len(found)} times")
    best = min(found, key=lambda e: e["rank"])
    out["modes"].append({
        "key": key, "title": title, "tier": tier, "lastWeek": hi,
        "weeksInTop100": len(found), "weekSet": sorted(e["week"] for e in found),
        "bestRank": {"rank": best["rank"], "week": best["week"], "start": best["start"], "score": best["score"]},
        "top": sorted(found, key=lambda e: -e["score"])[:5],
    })

js = ("/* Best PPC / Warzone runs for player %d (Huaxu, AP server). Snapshot of every week in the public top 100;\n"
      "   main.js re-checks the newest weeks live and merges them in. Generated by tools/update_runs.py. */\n"
      "window.BEST_RUNS = %s;\n") % (PLAYER, json.dumps(out, ensure_ascii=False, separators=(",", ":")))
open(OUT, "w", encoding="utf8").write(js)
print("wrote", OUT)
